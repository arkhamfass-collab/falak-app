/**
 * src/core/riseSetUtil.js
 * غلاف دفاعي حول riseLib.times() (مكتبة astronomia، فصل ميوس 15 - الشروق والعبور والغروب).
 *
 * علة مُثبَتة تجريبيا (انظر /tmp أو سجل العمل): في بعض الحالات تُقفز قيمة "العبور" المُصحَّحة
 * التي تُعيدها times() بمقدار يوم كامل تقريبا (86400 ثانية) عن القيمة الصحيحة، بسبب أن تصحيح
 * الزاوية الداخلي (الفرق بين الزاوية الساعية الخام ومضاعفاتها) لا يُطوَّق (wrap) إلى أقرب
 * مكافئ قبل استعماله كتصحيح صغير على التقدير التقريبي (approxTimes) - فحين يقع الحساب الخام
 * على "دورة" مجاورة (±360° = ±86400 ثانية)، تنزاح نتيجة العبور يوما كاملا رغم أن وقتها
 * (الساعة والدقيقة) داخل اليوم يكون صحيحا تماما. التحقق العملي (مكة، 2026-04-01) أظهر:
 *   rise diff ≈ -7.2s  (تصحيح طبيعي)
 *   set  diff ≈ +12.4s (تصحيح طبيعي)
 *   transit diff ≈ -86406.8s  (= -86400 - 6.8s؛ أي تصحيح طبيعي -6.8s + قفزة زائفة يوم كامل)
 *
 * الإصلاح هنا لا يُعدِّل الملف الموروث (نُفضّل عدم لمس كود موثّق مُتحقَّق منه مصدره)، بل يُطوِّق
 * ناتج times() إلى أقرب مكافئ لناتج approxTimes() (الذي يُضمَن ضمن [0, 86400) دائما) لكل من
 * الشروق والعبور والغروب على حدة - فيُلغى أي انزياح بمضاعفات يوم كامل مع الحفاظ الكامل على دقة
 * تصحيح ميوس الطبيعية (ثوان إلى دقائق قليلة).
 */

import riseLib from './astro/src/rise.js'

const SECS_PER_DAY = 86400

/** يُعيد قيمة مكافئة لـvalue (بفرق مضاعف صحيح لـperiod) وهي الأقرب إلى anchor */
function nearestEquivalent (value, anchor, period = SECS_PER_DAY) {
  const diff = value - anchor
  const wrapped = diff - period * Math.round(diff / period)
  return anchor + wrapped
}

const TWO_PI = 2 * Math.PI

/**
 * علة ثانية مُثبَتة تجريبيا (مختلفة كليا عن علة القفزة اليومية أعلاه): حين يعبر المطلع المستقيم
 * للجرم ٠/٣٦٠° خلال يومي الاستيفاء الثلاثي الثلاثة (أي يوم اعتدال ربيعي للشمس - مرة واحدة كل
 * عام، تماما بين يومين متتاليين كل سنة - أو عدة مرات شهريا للقمر، إذ يدور مطلعه كاملا كل نحو
 * ٢٧ يوما)، تستعمل riseLib.times() قيم ra3 الثلاث خاما (مثلا [358.3°, 359.2°, 0.14°]) في استيفاء
 * يفترض استمرارية الدالة - فيرى "قفزة" زائفة تناهز ٣٦٠° بين عنصرين متتاليين (والصحيح فرق صغير
 * دون درجة واحدة) فينحرف الاستيفاء كليا، منتجا نتائج عشوائية تماما (قد تبعد ساعات عن الصحيح) -
 * خلافا لعلة القفزة اليومية (فرق يوم كامل مضبوط تقريبا) التي يُصلحها nearestEquivalent أدناه.
 * التحقق العملي (خطوط طول/عروض متعددة، ٢٠٢٧-٠٣-٢٠ و٢٠٢٧-٠٣-٢١، يوم عبور المطلع المستقيم ٠/٣٦٠°
 * لتلك السنة بالضبط): transit/rise/set قبل الإصلاح ينحرف ساعات عن approxTimes (الفارق المتوقع
 * ثوان إلى دقائق قليلة فقط)، وبعده يعود للفارق الطبيعي في كل الحالات المفحوصة.
 * الإصلاح: "تطويق" (unwrap) المصفوفة الثلاثية نفسها قبل تمريرها لـriseLib.times - كل عنصر
 * (من الثاني فصاعدا) يُستبدل بأقرب مكافئ له (±2π×n) للعنصر الذي قبله (بعد تطويقه هو نفسه) -
 * فتصبح المتتابعة متصلة حقا (مثلا [358.3°, 359.2°, 360.14°]) دون أي تغيير في قيمتها الفعلية
 * (مكافئة تماما مودلو 2π) ودون أي تأثير على δ3 (الميل لا يدور حول ٣٦٠° أصلا، فلا يحتاج تطويقا).
 */
function unwrapContinuous (values) {
  const out = [values[0]]
  for (let i = 1; i < values.length; i++) {
    const prev = out[i - 1]
    const v = values[i]
    out.push(v + TWO_PI * Math.round((prev - v) / TWO_PI))
  }
  return out
}

/**
 * نظير آمن لـriseLib.times (نفس التوقيع والمُعاملات والنتيجة ونفس الاستثناءات المرفوعة
 * errorAboveHorizon/errorBelowHorizon عند عدم وجود عبور فعلي) - انظر توثيق rise.js.
 */
export function safeTimes (p, deltaTsec, h0, Th0, ra3, dec3) {
  const approx = riseLib.approxTimes(p, h0, Th0, ra3[1], dec3[1])
  const refined = riseLib.times(p, deltaTsec, h0, Th0, unwrapContinuous(ra3), dec3)
  return {
    rise: nearestEquivalent(refined.rise, approx.rise),
    transit: nearestEquivalent(refined.transit, approx.transit),
    set: nearestEquivalent(refined.set, approx.set)
  }
}

/**
 * علة رابعة - الأخطر أثرا من كل العلل السابقة في هذا الملف - مُثبَتة تجريبيا: "اليوم الخطأ".
 * كل من sun.js وmoon.js يُهيّئان حساب الشروق/الزوال/الغروب حول مرساة timeutil.utcCivilDayAnchorJD
 * (يوم UTC الذي يحوي *ظهر* المراقب المحلي) ثم يُفسِّران ناتج safeTimes أعلاه (ثوان ضمن [0,86400)
 * من تلك المرساة) كأنه "اليوم المحلي المطلوب" - بينما مرساة الظهر تلك تختلف عن منتصف الليل
 * المحلي الحقيقي بمقدار |utcOffsetHours| ساعة تماما (راجع توثيق timeutil.localMidnightJD
 * للتفصيل الكامل وسبب هذا الفرق). النتيجة: حين تسقط لحظة العبور الفعلية ضمن الساعات "المفقودة"
 * من تلك النافذة المُزاحة (شائع جدا لفروق توقيت كبيرة)، يُعاد عبور من يوم مجاور بدل اليوم المطلوب
 * نفسه - رغم وجود عبور صحيح من اليوم المطلوب أصلا. قياس تجريبي واسع (عيّنات عشوائية، خطوط عرض
 * وطول وتواريخ وفروق توقيت متنوعة): نحو ٢٥٪ من حسابات الشروق/الزوال/الغروب لكل من الشمس والقمر
 * تُصاب بهذه العلة - شديدة الخطورة هنا خاصة لأن sun.js هو الأساس الوحيد الذي تُحسَب عليه كل
 * مواقيت الصلاة الخمس في prayerTimes.js (فجر/شروق/ظهر/عصر/مغرب/عشاء وتوابعها).
 *
 * الإصلاح الجذري (لا يُعدِّل safeTimes أعلاه، بل يُضاف كمسار مستقل كليا يُستعمل بدلا منه حين
 * يُعثر على عبور صحيح به): بحث مباشر عن كل عبور (ارتفاع يعبر الحد صعودا/هبوطا للشروق/الغروب،
 * وزاوية ساعية تعبر الصفر صعودا للزوال) ضمن نافذة *اليوم المحلي الحقيقي* [localMidnightJdUT,
 * +1) - مباشرة عبر دالة "العيّنة" (sample) المُمرَّرة، بلا أي استيفاء تقريبي بين أيام متباعدة
 * ولا أي اعتماد على مرساة ظهر مُزاحة. مسح خشن (٢٠ دقيقة - آمن تماما: أقصى معدل تغيّر ارتفاع
 * مرصود عمليا لأسرع الجرمين هنا، القمر، قرب الأفق نحو ١٢°/الساعة أي ~٤° كل ٢٠ دقيقة، لا يسمح
 * بعبورين متتاليين يختفيان ضمن نافذة بهذا القصر لعبور الأفق السلس طبيعته) ثم بايسكشن دقيق
 * (<٠٫٠١ ثانية) لكل عبور يُعثر عليه. التحقق العملي الكامل وقياسات معدل الخطأ قبل/بعد: راجع سجل
 * العمل (measure_day_mismatch.mjs، measure_sun_day_mismatch.mjs، classify_mismatches.mjs).
 *
 * @param {number} localMidnightJdUT - من timeutil.localMidnightJD (لا utcCivilDayAnchorJD) -
 *   اللحظة العالمية المطابقة لمنتصف الليل المحلي الحقيقي لليوم المطلوب بالضبط.
 * @param {(jdUT:number) => {err:number, H:number}} sample - err = الارتفاع الحالي عند jdUT
 *   ناقص الحد (threshold) عند نفس اللحظة (قد يعتمد الحد على الزمن كنصف قطر/منظر القمر، أو يكون
 *   ثابتا كالشمس) - موجب فوق الحد (الجرم "مرئيا" بحسب هذا الحد)، سالب تحته.
 *   H = الزاوية الساعية بالدرجات، مُضيَّقة إلى [-180, 180) (كما تُرجعها horizontalFromEquatorial
 *   في كل من sun.js وmoon.js).
 * @returns {{rises:number[], sets:number[], transits:number[]}} كل عبور كـJD عالمي (UT) مضبوط
 *   دقيق مباشرة (لا حاجة لأي تصحيح نيوتن إضافي بعده - البايسكشن هنا يبلغ دقة <٠٫٠١ ثانية أصلا).
 *   مصفوفات (لا قيمة مفردة) لاحتواء الحالة النادرة جدا (خاصة للقمر، دورته ~٢٤س٥٠د) التي يقع
 *   فيها عبوران من النوع نفسه كاملين ضمن يوم مدني واحد (٢٤س٠٠د) - اختيار الأنسب (عادة الأول
 *   زمنيا) مسؤولية المستدعي؛ ومصفوفة فارغة حين لا يقع عبور من هذا النوع ضمن اليوم المطلوب أصلا
 *   (حالة طبيعية متوقَّعة، خاصة للقمر - لا علة بذاتها)، وعلى المستدعي وقتها استعمال تقدير
 *   safeTimes (أعلى هذا الملف) القديم احتياطا، حفاظا على تصرُّف "أقرب عبور من يوم مجاور" المعهود
 *   لتلك الحالة الحدية فقط دون أي تغيير فيها.
 */
const FIND_DAY_COARSE_STEP_DAYS = 20 * 60 / 86400 // 20 دقيقة
const FIND_DAY_BISECT_MAX_ITER = 50
const FIND_DAY_BISECT_CONVERGED_DAYS = 0.01 / 86400 // 0.01 ثانية

function bisectFindDayCrossing (loJd, hiJd, sample, field, risingWanted) {
  let lo = loJd, hi = hiJd
  for (let i = 0; i < FIND_DAY_BISECT_MAX_ITER; i++) {
    const mid = (lo + hi) / 2
    const v = sample(mid)[field]
    const isLowSide = risingWanted ? v < 0 : v >= 0
    if (isLowSide) lo = mid; else hi = mid
    if (hi - lo < FIND_DAY_BISECT_CONVERGED_DAYS) break
  }
  return (lo + hi) / 2
}

// عدد خطوات المسح الخشن ضمن يوم كامل (٢٤ ساعة / ٢٠ دقيقة = ٧٢ خطوة تماما)
const FIND_DAY_NUM_STEPS = Math.round(1 / FIND_DAY_COARSE_STEP_DAYS)

export function findDayCrossings (localMidnightJdUT, sample) {
  const rises = [], sets = [], transits = []
  let prevJd = localMidnightJdUT
  let prev = sample(prevJd)
  // ملحوظة دقة حسابية مهمة: نحسب كل خطوة بالضرب (localMidnightJdUT + i*step) بدل التجميع
  // بالجمع المتكرر (t += step داخل الحلقة) - فالجمع المتكرر لعدد عشري لا يُمثَّل بدقة كاملة في
  // الفاصلة العائمة (مثل خطوة ٢٠ دقيقة=0.0138888...يوم) يُراكم خطأ تقريب يتجاوز بسهولة أي عتبة
  // تسامح صغيرة (مثل 1e-9) بعد ٧٢ خطوة، خاصة إن كانت القيمة الأساسية (jd0) كبيرة (نحو 2.46 مليون
  // ليوميات جوليانية حديثة) - ما يُسبِّب توقُّف المسح خطوة واحدة أبكر من اللازم، فيُفوَّت تماما أي
  // عبور يقع في آخر ٢٠ دقيقة من اليوم (قبل منتصف الليل التالي بقليل) - علة مُثبَتة تجريبيا (راجع
  // سجل العمل: debug_residual.mjs، حالة 2025-09-08 lat=-54.1 lon=59.2 off=-3 حيث يقع غروب القمر
  // 23:46:xx محليا، أي ضمن آخر خطوة بالضبط، وكان يُفوَّت تماما قبل هذا الإصلاح). الضرب بدل الجمع
  // المتكرر يتجنّب تراكم الخطأ عبر التكرارات (لا خطأ "يتراكم"، فكل خطوة مُحسَبة من الصفر مباشرة).
  for (let i = 1; i <= FIND_DAY_NUM_STEPS; i++) {
    const t = localMidnightJdUT + i * FIND_DAY_COARSE_STEP_DAYS
    const cur = sample(t)
    if (prev.err < 0 && cur.err >= 0) rises.push(bisectFindDayCrossing(prevJd, t, sample, 'err', true))
    if (prev.err >= 0 && cur.err < 0) sets.push(bisectFindDayCrossing(prevJd, t, sample, 'err', false))
    // نتجاهل قفزة التطويق الزائفة عند ±١٨٠° (الزاوية الساعية تمر عبرها كل يوم مرة دون أن تكون
    // عبور زوال حقيقيا) - عبور الزوال الحقيقي الوحيد هو القفزة الصغيرة من سالب لموجب قرب الصفر.
    if (prev.H < 0 && cur.H >= 0 && (cur.H - prev.H) < 180) {
      transits.push(bisectFindDayCrossing(prevJd, t, sample, 'H', true))
    }
    prevJd = t; prev = cur
  }
  return { rises, sets, transits }
}

export default { safeTimes, findDayCrossings }
